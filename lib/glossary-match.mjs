// Сопоставление терминов глоссария с их падежными формами в тексте.
//
// Наивное совпадение по строке не годится: в тексте «гликоген» встречается
// как «гликогена», «гликогену», «гликогеном». А слишком вольная основа
// цепляет лишнее — «гликогенолиз» и «инсулинорезистентность» это другие
// понятия. Поэтому основа плюс закрытый список окончаний, и ничего больше.

/** Окончания по типу последней буквы слова */
const ENDINGS = {
  // существительные мужского рода на согласный: гликоген, инсулин
  consonant: ['', 'а', 'у', 'ом', 'е', 'ы', 'ов', 'ам', 'ами', 'ах', 'ой'],
  // на -а: глюкоза, липаза
  a: ['а', 'ы', 'е', 'у', 'ой', 'ою', 'ам', 'ами', 'ах'],
  // на -я: гипертрофия, энергия
  ya: ['я', 'и', 'ю', 'ей', 'ям', 'ями', 'ях', 'ии', 'ией'],
  // на -ь: желчь, соль
  soft: ['ь', 'и', 'ью', 'ей', 'ям', 'ями', 'ях'],
  // на -о/-е: ядро, поле
  o: ['о', 'а', 'у', 'ом', 'е', 'ы', 'ам', 'ами', 'ах'],
  // прилагательные: висцеральный, адаптивный
  adj: ['ый', 'ий', 'ой', 'ого', 'ому', 'ым', 'ом', 'ая', 'ой', 'ую', 'ое', 'ые', 'ых', 'ыми', 'его', 'ему', 'им', 'ей', 'ею', 'ее', 'ие', 'их', 'ими'],
}

const ADJ_SUFFIX = /(ый|ий|ой|ая|ое|ые|ым|ом|ую|ых|ого|ому|ими)$/

/** Разбор одного слова термина: основа + подходящий набор окончаний */
function wordPattern(word) {
  const w = word.toLowerCase()

  // Латиница, цифры, аббревиатуры — как есть, без склонения
  if (!/[а-яё]/.test(w)) return escapeRe(w)

  // Прилагательное
  if (w.length > 5 && ADJ_SUFFIX.test(w)) {
    const stem = w.replace(ADJ_SUFFIX, '')
    if (stem.length >= 4) return `${escapeRe(stem)}(?:${ENDINGS.adj.join('|')})`
  }

  const last = w.slice(-1)
  let stem = w
  let set = ENDINGS.consonant
  if (last === 'а') {
    stem = w.slice(0, -1)
    set = ENDINGS.a
  } else if (last === 'я') {
    stem = w.slice(0, -1)
    set = ENDINGS.ya
  } else if (last === 'ь') {
    stem = w.slice(0, -1)
    set = ENDINGS.soft
  } else if (last === 'о' || last === 'е') {
    stem = w.slice(0, -1)
    set = ENDINGS.o
  }

  // Слишком короткая основа даёт мусорные совпадения
  if (stem.length < 3) return escapeRe(w)
  return `${escapeRe(stem)}(?:${set.join('|')})?`
}

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

// В JS \b не работает с кириллицей, поэтому границы слова задаём вручную
const LEFT = '(?<![0-9A-Za-zА-Яа-яЁё-])'
const RIGHT = '(?![0-9A-Za-zА-Яа-яЁё-])'

/**
 * Термины, которые подсвечивать не нужно: обиходные слова, знакомые
 * любому читателю. Цель подсказок — сложные слова, а не все подряд.
 */
export const SKIP = new Set([
  'вода', 'сон', 'жир', 'вес', 'еда', 'соль', 'сахар', 'мышца', 'мышцы', 'белок',
  'калория', 'калории', 'голод', 'стресс', 'привычка', 'тело', 'кровь', 'кожа',
  'мозг', 'сила воли', 'движение', 'отдых', 'возраст', 'пол', 'рост',
])

/** Стоит ли вообще подсвечивать этот термин */
export function isHighlightable(term) {
  const name = term.name.replace(/\s*\([^)]*\)\s*/g, ' ').trim()
  if (SKIP.has(name.toLowerCase())) return false
  if (name.length < 4) return false
  // Слишком длинные словосочетания в тексте дословно почти не встречаются
  if (name.split(/\s+/).length > 3) return false
  return true
}

/** Регулярное выражение, ловящее термин во всех падежных формах */
export function buildPattern(term) {
  // Скобочную расшифровку в поиске не используем: в тексте её нет
  const name = term.name.replace(/\s*\([^)]*\)\s*/g, ' ').trim()
  const words = name.split(/\s+/).filter(Boolean)
  const body = words.map(wordPattern).join('\\s+')
  return new RegExp(`${LEFT}(${body})${RIGHT}`, 'iu')
}

/**
 * Собирает матчер из списка терминов.
 * Длинные термины проверяются первыми: «висцеральный жир» должен выиграть
 * у «жира», иначе подсветится только часть словосочетания.
 */
export function buildMatcher(terms) {
  return terms
    .filter(isHighlightable)
    .map((t) => ({ term: t, re: buildPattern(t) }))
    .sort((a, b) => b.term.name.length - a.term.name.length)
}
